"""천문 계산 — 삭(朔) 시각과 태양 황경.

역법 규칙은 여기 없다. 어느 삭이 음력 1월인지, 윤달을 어디에 두는지는
rules/kr/lunar.py 가 정한다. 이 파일은 "언제 삭인가", "언제 태양 황경이 270°가
되는가"까지만 답한다.

둘을 나눈 이유는 틀리는 방식이 다르기 때문이다. 이쪽은 급수를 잘라 쓰고 ΔT 를
추정하므로 시각이 초~분 단위로 어긋난다. 저쪽은 치윤법 해석 때문에 달 번호가
통째로 밀린다. 한 파일에 두면 설날이 하루 밀렸을 때 어느 쪽이 원인인지 구분되지
않는다. 나눠 두면 이 파일은 "시각이 맞나", 저 파일은 "달 번호가 맞나"로 각각
검증된다.

--------------------------------------------------------------------------
왜 UTC+8 라이브러리를 그대로 쓰면 안 되는가
--------------------------------------------------------------------------
음력 초하루는 삭이 "든 날"이다. 삭 시각 자체가 아니라 그 시각이 속한 날짜다.
그 날짜는 어느 시간대에서 보느냐에 따라 갈린다.

    삭이 UTC 15:30 이면  → UTC+8 로는 23:30, 같은 날
                          → KST(+9) 로는 00:30, 다음 날

한국 역서는 KST 기준이고 중국 역서는 UTC+8 기준이다. 그래서 중국 음력
라이브러리는 이 구간에서 하루 어긋난다. 설날이 하루 밀리면 연휴 3일이 통째로
밀리고, 대체공휴일까지 따라 틀린다.

이 파일은 모든 시각을 KST 로 옮긴 뒤 날짜를 뽑는다. kst_moment() 가 그 자리다.
그 함수는 자정으로부터의 분(minutes)도 함께 돌려준다. 계산 오차가 하루를 가를
만큼 자정에 가까운지 호출자가 볼 수 있어야 하기 때문이다.

--------------------------------------------------------------------------
쓰는 급수와 그 정확도
--------------------------------------------------------------------------
Meeus, Astronomical Algorithms 2판.

  삭 시각   제49장. 절단 ELP-2000/82 기반. 문헌이 밝히는 오차는 현대 구간에서
            평균 수 초, 최대 20 초 안쪽이다.
  태양 황경 제25장 저정밀도 식. 문헌이 밝히는 오차는 약 0.01°.
            시간으로 환산하면 약 15 분이다(태양은 하루에 약 0.9856° 간다).

두 값의 문헌 오차는 그대로 믿지 않는다. 우리가 옮겨 적은 계수가 맞는지는 별개
문제이고, 그건 실측 대조로만 확인된다. tests/test_astro.py 와
tests/test_lunar.py 가 KASI 특일정보 응답과 대조한다.

--------------------------------------------------------------------------
이 정확도가 문제가 되는 자리
--------------------------------------------------------------------------
두 값 모두 "그 시각이 KST 로 어느 날인가"로만 쓰인다. 그래서 오차는 시각이
KST 자정에 가까울 때만 결과를 바꾼다.

    삭이 자정에서 20 초 안쪽   → 초하루가 하루 갈릴 수 있다
    중기가 자정에서 15 분 안쪽 → 윤달 자리가 갈릴 수 있다

여유가 실제로 얼마나 되는지는 짐작하지 않는다. kst_moment() 가 돌려주는 분 값을
테스트가 모아서 최소 여유를 보고한다. 여유가 오차보다 크면 그 구간에서는
정확도가 결과를 바꾸지 못한다는 것이 확인된 것이고, 작아지면 그때 드러난다.

여유가 부족한 날짜가 나오면 급수를 늘리는 것(VSOP87)이 한 방법이지만, 그래도
남는 한계가 있다. 한국의 공식 역서는 한국천문연구원이 확정해 발표하는 값이다.
계산과 발표가 갈리면 발표가 맞다. 우리 계산은 원리적으로 2차 소스이며,
그래서 KASI 대조가 장식이 아니라 최종 판정이다.

--------------------------------------------------------------------------
ΔT
--------------------------------------------------------------------------
급수는 역학시(TT)를 준다. 날짜를 뽑으려면 세계시(UT)로 옮겨야 하고 그 차이가
ΔT 다. ΔT 는 지구 자전 변동이라 예측이 아니라 관측값이고, 미래는 추정이다.

Espenak & Meeus 다항식을 쓴다. 2005~2050 구간 식은 실측이 그 뒤 평평해지면서
2020 년대에 2~3 초 높게 나온다. 우리가 신경 쓰는 단위는 분이므로 이 오차는
결과를 바꾸지 못한다. 다만 2050 년 이후는 추정 폭이 수십 초로 벌어지므로,
그 구간을 확정처럼 다루지 말 것.
"""

from __future__ import annotations

import math
from datetime import date

J2000 = 2451545.0
KST_OFFSET_DAYS = 9 / 24

# 태양이 하루에 가는 평균 황경. 중기 시각을 뉴턴법으로 좁힐 때 기울기로 쓴다.
# 실제 속도는 근일점 근처에서 3% 남짓 빠르므로 반복이 필요하다.
SOLAR_DEGREES_PER_DAY = 0.98565

# 삭에서 삭까지의 평균 길이. 달 번호를 추정할 때만 쓴다.
SYNODIC_MONTH_DAYS = 29.530588861

# 중기 사이 평균 간격. 다음 중기의 초기 추정값으로만 쓴다.
_MID_TERM_INTERVAL_DAYS = 30.44

_TERM_TOLERANCE_DEG = 1e-7   # 시간으로 약 0.01 초
_TERM_MAX_ITER = 30


class AstroError(ValueError):
    """천문 계산이 답을 내지 못했다."""


# ---------------------------------------------------------------------------
# 율리우스일 ↔ 그레고리력
# ---------------------------------------------------------------------------


def julian_day(day: date) -> float:
    """그 날짜 0 시의 율리우스일. 그레고리력만 다룬다."""
    year, month = day.year, day.month
    if month <= 2:
        year -= 1
        month += 12
    century = year // 100
    gregorian = 2 - century + century // 4
    return (
        math.floor(365.25 * (year + 4716))
        + math.floor(30.6001 * (month + 1))
        + day.day
        + gregorian
        - 1524.5
    )


def _civil_from_day_number(number: int) -> date:
    """floor(JD + 0.5) → 달력 날짜. Meeus 제7장."""
    if number < 2299161:
        a = number
    else:
        alpha = int((number - 1867216.25) / 36524.25)
        a = number + 1 + alpha - alpha // 4
    b = a + 1524
    c = int((b - 122.1) / 365.25)
    d = int(365.25 * c)
    e = int((b - d) / 30.6001)
    day = b - d - int(30.6001 * e)
    month = e - 1 if e < 14 else e - 13
    year = c - 4716 if month > 2 else c - 4715
    return date(year, month, day)


def _decimal_year(jd: float) -> float:
    """ΔT 조회용 연도. TT/UT 차이(약 70 초)는 이 용도에 영향이 없다."""
    day = _civil_from_day_number(math.floor(jd + 0.5))
    return day.year + (day.month - 0.5) / 12.0


# ---------------------------------------------------------------------------
# ΔT — Espenak & Meeus 다항식
# ---------------------------------------------------------------------------


def delta_t_seconds(year: float) -> float:
    """TT − UT, 초.

    구간을 벗어나면 장기식으로 흘린다. 예외를 던지지 않는 이유는 이 값이
    분 단위 판정에만 쓰여서, 범위 밖에서도 답이 쓸모없어지지는 않기 때문이다.
    범위 밖을 확정처럼 다루지 않는 것은 coverage 가 맡는다.
    """
    if 1900 <= year < 1920:
        t = year - 1900
        return -2.79 + t * (1.494119 + t * (-0.0598939 + t * (0.0061966 + t * -0.000197)))
    if 1920 <= year < 1941:
        t = year - 1920
        return 21.20 + t * (0.84493 + t * (-0.076100 + t * 0.0020936))
    if 1941 <= year < 1961:
        t = year - 1950
        return 29.07 + 0.407 * t - t**2 / 233 + t**3 / 2547
    if 1961 <= year < 1986:
        t = year - 1975
        return 45.45 + 1.067 * t - t**2 / 260 - t**3 / 718
    if 1986 <= year < 2005:
        t = year - 2000
        return 63.86 + t * (
            0.3345
            + t * (-0.060374 + t * (0.0017275 + t * (0.000651814 + t * 0.00002373599)))
        )
    if 2005 <= year < 2050:
        t = year - 2000
        return 62.92 + t * (0.32217 + t * 0.005589)
    if 2050 <= year <= 2150:
        return -20 + 32 * ((year - 1820) / 100) ** 2 - 0.5628 * (2150 - year)
    u = (year - 1820) / 100
    return -20 + 32 * u * u


def _delta_t_days(jd: float) -> float:
    return delta_t_seconds(_decimal_year(jd)) / 86400.0


# ---------------------------------------------------------------------------
# KST 로 옮기기
# ---------------------------------------------------------------------------


def kst_moment(jde: float) -> tuple:
    """역학시 율리우스일 → (KST 날짜, 그 날 자정으로부터 지난 분).

    분 값을 함께 돌려주는 것이 요점이다. 날짜만 돌려주면 그 날짜가 자정에서
    30 초 떨어진 아슬아슬한 값인지, 12 시간 떨어진 안전한 값인지 구분되지 않는다.
    급수 오차가 결과를 바꿀 수 있는 자리인지는 이 값으로만 판단된다.
    """
    jd_ut = jde - _delta_t_days(jde)
    shifted = jd_ut + KST_OFFSET_DAYS + 0.5
    day_number = math.floor(shifted)
    minutes = (shifted - day_number) * 1440.0
    return _civil_from_day_number(day_number), minutes


def minutes_from_midnight(jde: float) -> float:
    """KST 자정까지의 거리(분). 자정 직전이면 작은 값으로 되돌린다.

    0 시 05 분과 23 시 55 분은 둘 다 자정에서 5 분이다. 여유를 볼 때는 어느
    쪽인지가 아니라 얼마나 가까운지가 문제다.
    """
    minutes = kst_moment(jde)[1]
    return min(minutes, 1440.0 - minutes)


