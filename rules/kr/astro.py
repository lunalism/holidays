"""천문 계산 — 삭(朔) 시각과 태양 황경.

역법 규칙은 여기 없다. 어느 삭이 음력 1월인지, 윤달을 어디에 두는지는
rules/kr/lunar.py 가 정한다. 이 파일은 "언제 삭인가", "언제 태양 황경이 270°가
되는가"까지만 답한다.

둘을 나눈 이유는 틀리는 방식이 다르기 때문이다. 이쪽은 급수를 잘라 쓰고 ΔT 를
추정하므로 시각이 초~분 단위로 어긋난다. 저쪽은 치윤법 해석 때문에 달 번호가
통째로 밀린다. 한 파일에 두면 설날이 하루 밀렸을 때 어느 쪽이 원인인지 구분되지
않는다. 나눠 두면 이 파일은 "시각이 맞나", 저 파일은 "달 번호가 맞나"로 각각
검증된다.

--------------------------------------------------------------------------
왜 UTC+8 라이브러리를 그대로 쓰면 안 되는가
--------------------------------------------------------------------------
음력 초하루는 삭이 "든 날"이다. 삭 시각 자체가 아니라 그 시각이 속한 날짜다.
그 날짜는 어느 시간대에서 보느냐에 따라 갈린다.

    삭이 UTC 15:30 이면  → UTC+8 로는 23:30, 같은 날
                          → KST(+9) 로는 00:30, 다음 날

한국 역서는 KST 기준이고 중국 역서는 UTC+8 기준이다. 그래서 중국 음력
라이브러리는 이 구간에서 하루 어긋난다. 설날이 하루 밀리면 연휴 3일이 통째로
밀리고, 대체공휴일까지 따라 틀린다.

이 파일은 모든 시각을 KST 로 옮긴 뒤 날짜를 뽑는다. kst_moment() 가 그 자리다.
그 함수는 자정으로부터의 분(minutes)도 함께 돌려준다. 계산 오차가 하루를 가를
만큼 자정에 가까운지 호출자가 볼 수 있어야 하기 때문이다.

--------------------------------------------------------------------------
쓰는 급수와 그 정확도
--------------------------------------------------------------------------
Meeus, Astronomical Algorithms 2판.

  삭 시각   제49장. 절단 ELP-2000/82 기반. 문헌이 밝히는 오차는 현대 구간에서
            평균 수 초, 최대 20 초 안쪽이다.
  태양 황경 제25장 저정밀도 식. 문헌이 밝히는 오차는 약 0.01°.
            시간으로 환산하면 약 15 분이다(태양은 하루에 약 0.9856° 간다).

두 값의 문헌 오차는 그대로 믿지 않는다. 우리가 옮겨 적은 계수가 맞는지는 별개
문제이고, 그건 실측 대조로만 확인된다. tests/test_astro.py 와
tests/test_lunar.py 가 KASI 특일정보 응답과 대조한다.

--------------------------------------------------------------------------
이 정확도가 문제가 되는 자리
--------------------------------------------------------------------------
두 값 모두 "그 시각이 KST 로 어느 날인가"로만 쓰인다. 그래서 오차는 시각이
KST 자정에 가까울 때만 결과를 바꾼다.

    삭이 자정에서 20 초 안쪽   → 초하루가 하루 갈릴 수 있다
    중기가 자정에서 15 분 안쪽 → 윤달 자리가 갈릴 수 있다

여유가 실제로 얼마나 되는지는 짐작하지 않는다. kst_moment() 가 돌려주는 분 값을
테스트가 모아서 최소 여유를 보고한다. 여유가 오차보다 크면 그 구간에서는
정확도가 결과를 바꾸지 못한다는 것이 확인된 것이고, 작아지면 그때 드러난다.

여유가 부족한 날짜가 나오면 급수를 늘리는 것(VSOP87)이 한 방법이지만, 그래도
남는 한계가 있다. 한국의 공식 역서는 한국천문연구원이 확정해 발표하는 값이다.
계산과 발표가 갈리면 발표가 맞다. 우리 계산은 원리적으로 2차 소스이며,
그래서 KASI 대조가 장식이 아니라 최종 판정이다.

--------------------------------------------------------------------------
시각을 날짜로 옮기는 일은 여기 없다
--------------------------------------------------------------------------
ΔT 를 빼서 세계시로 옮기는 것도, 율리우스일을 달력 날짜로 바꾸는 것도,
오프셋을 더해 자정 경계를 자르는 것도 나라와 무관하다. 그래서 core/timekeeping.py
에 있다.

이 파일에 남는 것은 그 계산에 한국 값을 물리는 일이다. KST_OFFSET_DAYS 가
그 값이고 kst_moment() 가 그 바인딩이다. 즉 이 파일은 계속 한국 층이다 —
"9 시간"이라는 선택이 어디서 내려졌는지 찾으려면 여기를 보면 된다.
"""

from __future__ import annotations

