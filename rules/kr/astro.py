def new_moon_jde(k: int) -> float:
    """k 번째 삭의 역학시 율리우스일. k 는 2000-01-06 삭을 0 으로 센다."""
    if k != int(k):
        raise AstroError(f"k 는 정수여야 한다(삭). 받은 값: {k!r}")
    k = int(k)
    t = k / 1236.85
    t2 = t * t
    t3 = t2 * t
    t4 = t3 * t

    jde = (
        2451550.09766
        + 29.530588861 * k
        + 0.00015437 * t2
        - 0.000000150 * t3
        + 0.00000000073 * t4
    )

    eccentricity = 1 - 0.002516 * t - 0.0000074 * t2
    sun_anomaly = math.radians(
        2.5534 + 29.10535670 * k - 0.0000014 * t2 - 0.00000011 * t3
    )
    moon_anomaly = math.radians(
        201.5643 + 385.81693528 * k + 0.0107582 * t2 + 0.00001238 * t3 - 0.000000058 * t4
    )
    latitude_arg = math.radians(
        160.7108 + 390.67050284 * k - 0.0016118 * t2 - 0.00000227 * t3 + 0.000000011 * t4
    )
    node = math.radians(124.7746 - 1.56375588 * k + 0.0020672 * t2 + 0.00000215 * t3)

    for coefficient, moon, sun, latitude, power in _NEW_MOON_TERMS:
        angle = moon * moon_anomaly + sun * sun_anomaly + latitude * latitude_arg
        jde += coefficient * eccentricity**power * math.sin(angle)

    jde += -0.00017 * math.sin(node)

    for coefficient, constant, per_k, per_t2 in _NEW_MOON_PLANETARY:
        jde += coefficient * math.sin(math.radians(constant + per_k * k + per_t2 * t2))

    return jde


def new_moon_k_near(day: date) -> int:
    """그 날짜 근처 삭의 k. 정확하지 않다. 탐색 시작점으로만 쓸 것."""
    fraction = (day.timetuple().tm_yday - 0.5) / 365.25
    return round((day.year + fraction - 2000.0) * 12.3685)


def month_start_k(day: date) -> int:
    """그 날짜가 속한 삭망월의 k. 즉 그 날짜 이전(포함) 마지막 삭.

    k 추정이 한두 달 어긋날 수 있으므로 양방향으로 걸어 확정한다.
    추정값을 그대로 믿으면 연말·연초에서 조용히 한 달 밀린다.
    """
    k = new_moon_k_near(day)
    for _ in range(_TERM_MAX_ITER):
        if kst_moment(new_moon_jde(k))[0] > day:
            k -= 1
        elif kst_moment(new_moon_jde(k + 1))[0] <= day:
            k += 1
        else:
            return k
    raise AstroError(f"{day} 가 속한 삭망월을 찾지 못했다.")


# ---------------------------------------------------------------------------
# 태양 황경 — Meeus 제25장 (저정밀도)
# ---------------------------------------------------------------------------


def apparent_solar_longitude(jde: float) -> float:
    """겉보기 태양 황경(도). 장동과 광행차를 포함한다."""
    t = (jde - J2000) / 36525.0
    mean_longitude = 280.46646 + 36000.76983 * t + 0.0003032 * t * t
    anomaly = math.radians(357.52911 + 35999.05029 * t - 0.0001537 * t * t)
    center = (
        (1.914602 - 0.004817 * t - 0.000014 * t * t) * math.sin(anomaly)
        + (0.019993 - 0.000101 * t) * math.sin(2 * anomaly)
        + 0.000289 * math.sin(3 * anomaly)
    )
    node = math.radians(125.04 - 1934.136 * t)
    return (mean_longitude + center - 0.00569 - 0.00478 * math.sin(node)) % 360.0


def solar_term_jde(longitude: float, guess: float) -> float:
    """태양 황경이 그 값이 되는 시각. guess 근처의 해를 찾는다.

    guess 가 며칠 어긋나도 수렴하지만 한 달 이상 어긋나면 옆 해로 넘어간다.
    호출자가 30 일 안쪽 추정을 주는 것을 전제로 한다.
    """
    jde = guess
    for _ in range(_TERM_MAX_ITER):
        gap = (longitude - apparent_solar_longitude(jde) + 180.0) % 360.0 - 180.0
        if abs(gap) < _TERM_TOLERANCE_DEG:
            return jde
        jde += gap / SOLAR_DEGREES_PER_DAY
    raise AstroError(f"황경 {longitude}° 시각이 수렴하지 않았다(시작 {guess}).")


def winter_solstice_jde(year: int) -> float:
    """그 해 동지(황경 270°)의 역학시 율리우스일.

    동지는 세(歲)의 기준점이다. 동지가 든 달이 음력 11 월이고 거기서부터
    달 번호를 센다. lunar.py 참조.
    """
    return solar_term_jde(270.0, julian_day(date(year, 12, 21)))
