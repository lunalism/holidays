"""발행 — 만든 피드를 파일로 내는 자리.

--------------------------------------------------------------------------
왜 core/ics.py 가 아닌가
--------------------------------------------------------------------------
두 가지 때문이다.

1. core/ics.py 는 iCalendar 직렬화 모듈이고 publish() 는 iCalendar 를 모른다.
   바이트를 읽고 바이트를 쓸 뿐이다. VCALENDAR 인지 아닌지 묻지 않고, 무엇이
   공휴일인지도 모른다.

2. core/ics.py 의 모듈 수준 import 에 os 와 pathlib.Path 가 없다. 순수
   직렬화 모듈에 파일시스템 의존을 들이지 않는다 — 들이는 순간 그 모듈을
   부르는 쪽이 디스크를 건드릴 수 있게 되고, 같은 입력으로 같은 바이트가
   나온다는 보장을 코드로 읽어 내기 어려워진다.

--------------------------------------------------------------------------
core 는 어느 나라 피드인지 모른다
--------------------------------------------------------------------------
경로도 만드는 방법도 인자로 받는다. rules/<국가>/feed.py 의 FEED_PATH 나
build() 를 이름으로 참조하면 core/ → rules/ 방향이 생긴다. 그 방향은 금지다
(core/__init__.py, README.md). 인자로 받으면 생기지 않는다.
"""

from __future__ import annotations

import os
from pathlib import Path

from core import ics


def publish(build_body, path: Path) -> Path:
    """피드를 파일로 낸다. 이전 발행본을 읽고, 새로 만들고, 원자적으로 바꾼다.

    build_body 는 previous(bytes | None)를 받아 새 피드의 바이트를 돌려주는
    콜러블이다. 시계도 국가별 상수도 그 클로저가 들고 있다 — 여기서는 읽지
    않는다.

    ----------------------------------------------------------------------
    읽기와 쓰기를 쪼개지 않는다
    ----------------------------------------------------------------------
    publish(body, path) 처럼 "이미 만든 바이트를 받아 쓰기만" 하는 모양으로
    두지 않는다. 그러면 이전 발행본을 언제 읽을지가 호출부의 몫이 되고,
    호출부가 순서를 틀릴 수 있게 된다. 틀리면 이전 발행본이 사라진 뒤에야
    알게 된다 — SEQUENCE 의 진실 공급원이 그 파일이므로(core/ics.py 의
    _sequences() 참조) 사라진 뒤에는 어느 쪽이 맞는지 우리 쪽에서 알 방법이
    없다.

    읽기와 쓰기를 한 함수 안에서 순서대로 하는 것, 그것이 이 함수의 존재
    이유다. 쪼개자는 제안이 오면 여기를 먼저 읽을 것.

    ----------------------------------------------------------------------
    왜 stdout 리다이렉션을 쓰지 않는가
    ----------------------------------------------------------------------
    이 피드는 자기 자신의 직전 판을 입력으로 받는다. 그래서

        python -m <발행 모듈> > <피드 파일>

    는 쓸 수 없다. 셸이 프로세스를 띄우기 전에 대상 파일을 먼저 비우므로,
    읽을 이전 발행본이 사라진 뒤에 프로그램이 시작한다. 지금 구현에서는 빈
    파일이 파싱에 실패해 빌드가 멈추지만, 그때는 이미 발행본이 지워진 뒤라
    git 말고는 되돌릴 방법이 없다.

    읽기와 쓰기를 한 함수 안에서 순서대로 하고, 쓰기는 같은 디렉터리의 임시
    파일에 한 뒤 os.replace 로 바꾼다. 같은 파일시스템 안의 replace 는
    원자적이라 중간에 죽어도 반쪽짜리 피드가 남지 않는다.

    임시 파일을 같은 디렉터리에 두는 것도 그 때문이다. /tmp 에 만들면 파일
    시스템이 달라질 수 있고, 그러면 replace 가 복사로 떨어져 원자성이 깨진다.

    ----------------------------------------------------------------------
    path 에 기본값을 두지 않는다
    ----------------------------------------------------------------------
    core 는 어느 파일인지 모른다. 기본값을 두려면 여기에 국가별 경로가
    들어와야 한다.
    """
    if not ics.UID_DOMAIN_CONFIRMED:
        raise ics.IcsError(
            f"UID 네임스페이스 {ics.UID_DOMAIN!r} 가 확정되지 않아 발행하지 않는다.\n"
            "한 번 발행하면 UID 를 바꿀 수 없다. 바꾸면 구독자 캘린더에서 모든 "
            "공휴일이 삭제 + 재생성으로 나타난다.\n"
            "확정했다면 core/ics.py 의 UID_DOMAIN_CONFIRMED 를 True 로 둘 것. "
            "그 커밋이 곧 확정 기록이다.\n"
            "발행 없이 내용만 보려면 build() 를 쓸 것 — 그쪽은 막지 않는다."
        )

    previous = path.read_bytes() if path.exists() else None
    body = build_body(previous)

    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_bytes(body)
    os.replace(tmp, path)
    return path
